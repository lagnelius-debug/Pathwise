def main(path):
    text = open(path, encoding="utf-8").read()
    start = text.index("local global_classic = {")
    end = text.index("local global_tbc = {", start)
    factions = {}
    faction = source = None
    for line in text[start:end].splitlines():
        m = re.match(r'^  \["(Horde|Alliance)"\] = \{', line)
        if m:
            faction, source = m.group(1), None
            factions[faction] = {}
            continue
        m = re.match(r'^    \[(\d+)\] = \{', line)
        if m and faction:
            source = int(m.group(1))
            factions[faction][source] = {"name": None, "to": {}}
            continue
        if re.match(r'^    \["', line):
            source = None  # (keyed by name: started by gossip)
            continue
        if source is None or faction is None:
            continue
        m = re.match(r'^      \["name"\] = "((?:[^"\\]|\\.)*)",', line)
        if m:
            factions[faction][source]["name"] = m.group(1)
            continue
        m = re.match(r'^      \[(\d+)\] = (\d+),', line)
        if m:
            factions[faction][source]["to"][int(m.group(1))] = int(m.group(2))
    out = [HEADER, "Pathwise.Data.FlightTimes = {"]
    for faction in ("Alliance", "Horde"):
        out.append("  %s = {" % faction)
        for source in sorted(factions.get(faction, {})):
            node = factions[faction][source]
            if not node["to"]:
                continue
            name = node["name"]
            out.append("    [%d] = {%s" % (source, (" -- " + name) if name else ""))
            items = ["[%d] = %d," % kv for kv in sorted(node["to"].items())]
            for i in range(0, len(items), 8):
                out.append("      " + " ".join(items[i:i + 8]))
            out.append("    },")
        out.append("  },")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
