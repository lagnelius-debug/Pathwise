"""Builds Data/Classic/FlightTimes.lua from the InFlight addon's recorded
Classic Era flight times (https://github.com/LudiusMaximus/InFlight, MIT).

Usage: python3 -I tools/import_flight_times.py <InFlight/Defaults.lua> > Data/Classic/FlightTimes.lua

The file is read as text (never run): the `global_classic` table, keyed
faction -> source taxi node ID -> destination taxi node ID -> seconds.
Entries keyed by name (flights started from a gossip option) are skipped.
"""
