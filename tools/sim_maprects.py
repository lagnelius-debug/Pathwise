#!/usr/bin/env python3
"""Writes tests/sim/MapRects.lua: the world rectangle of every Classic Era
map (UiMapAssignment from wago.tools), for the real-data simulations
(tests/sim). Map position -> world yards, as the game's C_Map does.

Usage:
  curl -sS -o UiMapAssignment.csv "https://wago.tools/db2/UiMapAssignment/csv?build=1.15.9.70576"
  python3 -I tools/sim_maprects.py UiMapAssignment.csv 1.15.9.70576 > tests/sim/MapRects.lua
"""
import csv
import sys


def main():
    path = sys.argv[1]
    build = sys.argv[2] if len(sys.argv) > 2 else "?"
    text = open(path, encoding="utf-8").read()
    rects = {}
    for row in csv.DictReader(text.splitlines()):
        # The whole map (0-1 both ways), its first assignment.
        if (row["UiMin_0"], row["UiMin_1"], row["UiMax_0"], row["UiMax_1"]) != ("0", "0", "1", "1"):
            continue
        ui_map, order = int(row["UiMapID"]), int(row["OrderIndex"])
        if ui_map in rects and rects[ui_map][0] <= order:
            continue
        # Region: min x, y, z, max x, y, z (x north, y west).
        min_x, min_y = float(row["Region_0"]), float(row["Region_1"])
        max_x, max_y = float(row["Region_3"]), float(row["Region_4"])
        rects[ui_map] = (order, int(row["MapID"]), max_x, max_y, min_x, min_y)
    out = ["-- Generated by tools/sim_maprects.py from wago.tools (UiMapAssignment, build %s)." % build,
           "-- [uiMapID] = { continent, top, left, bottom, right } in world yards.",
           "return {"]
    for ui_map in sorted(rects):
        _, cont, top, left, bottom, right = rects[ui_map]
        out.append("  [%d] = { continent = %d, top = %.3f, left = %.3f, bottom = %.3f, right = %.3f }," % (
            ui_map, cont, top, left, bottom, right))
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
